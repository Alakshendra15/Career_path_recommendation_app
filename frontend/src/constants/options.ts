const UPPER = new Set(['sql', 'html', 'css', 'oop', 'nlp', 'eda', 'orm', 'rest api', 'ml', 'aws', 'gcp', 'etl', 'sas', 'sap', 'vba', 'spss', 'ssis', 'ci/cd', 'nosql']);
const SPECIAL: Record<string, string> = {
  javascript: 'JavaScript', 'c#': 'C#', go: 'Go', r: 'R', azure: 'Azure', spark: 'Spark', kafka: 'Kafka', airflow: 'Airflow', kubernetes: 'Kubernetes', terraform: 'Terraform', snowflake: 'Snowflake', databricks: 'Databricks', bigquery: 'BigQuery', hadoop: 'Hadoop', matlab: 'MATLAB', jira: 'Jira', powerpoint: 'PowerPoint', bash: 'Bash', typescript: 'TypeScript', 'node.js': 'Node.js', 'power bi': 'Power BI',
  'scikit-learn': 'scikit-learn', tensorflow: 'TensorFlow', pytorch: 'PyTorch', mongodb: 'MongoDB',
  fastapi: 'FastAPI', 'c++': 'C++', 'data structures': 'Data Structures', ai: 'AI', ui: 'UI', apis: 'APIs',
};

/** 'power bi' -> 'Power BI' for display; unknown / custom skills are just capitalised. */
export function labelSkill(skill: string): string {
  const key = skill.trim().toLowerCase();
  if (SPECIAL[key]) return SPECIAL[key];
  if (UPPER.has(key)) return key.toUpperCase();
  return key.replace(/\b\w/g, (c) => c.toUpperCase());
}
